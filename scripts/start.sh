#!/usr/bin/env bash
# FileGrid PPC - starts the whole system with a single command (ADR-002). From the repo root:
#   ./scripts/start.sh [--show-passwords]
# 1) checks Docker Compose >= 2.20; 2) creates .env with random secrets if missing (and fills in missing
# variables); 3) docker compose up -d --build; 4) waits for api health; 5) prints the URL and the test users.
set -euo pipefail

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd -- "$repo_root"
env_file=.env
health_timeout=${FILEGRID_START_TIMEOUT:-600}

info() { printf '==> %s\n' "$*"; }
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

show_passwords=false
if (($# > 0)); then
    if (($# != 1)) || [[ "$1" != --show-passwords ]]; then
        fail "Usage: $0 [--show-passwords]"
    fi
    show_passwords=true
fi

# --- 1. Docker and Docker Compose -------------------------------------------------------------------------------
command -v docker >/dev/null 2>&1 || fail "docker command not found. Install Docker (Engine or Desktop)."
docker info >/dev/null 2>&1 || fail "Docker is not responding. Start Docker and try again."
compose_version=$(docker compose version --short 2>/dev/null) ||
    fail "the Docker Compose v2 plugin (docker compose) is missing."
compose_version=${compose_version#v}
IFS=. read -r c_major c_minor _ <<<"$compose_version"
if ! [[ "$c_major" =~ ^[0-9]+$ && "${c_minor%%[!0-9]*}" =~ ^[0-9]+$ ]] ||
   ((c_major < 2 || (c_major == 2 && ${c_minor%%[!0-9]*} < 20))); then
    fail "Docker Compose $compose_version is too old; 2.20 or newer is required (for include)."
fi
info "Docker Compose $compose_version"

# --- 2. .env with random secrets ---------------------------------------------------------------------------------
# Alphanumeric password with at least one upper, one lower and one digit (SQL Server policy, CHECK_POLICY = ON).
random_password() {
    local length=${1:-24} value
    while :; do
        value=$(head -c 512 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9')
        value=${value:0:length}
        if ((${#value} == length)) && [[ "$value" =~ [A-Z] && "$value" =~ [a-z] && "$value" =~ [0-9] ]]; then
            printf '%s' "$value"
            return
        fi
    done
}
random_base64() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }

# Value of a .env variable (empty if missing).
env_value() { sed -n "s/^$1=//p" "$env_file" 2>/dev/null | tail -n 1 | tr -d '\r'; }

created_env=false
if [[ ! -f "$env_file" ]]; then
    (umask 077 && printf '# Generated by scripts/start.* at %s. Do NOT commit (it is in .gitignore).\n' "$(date -u +%FT%TZ)" >"$env_file")
    created_env=true
fi

added=()
# Adds the variable if missing or empty; existing values are never changed
# (the SQL passwords are already baked into the mssql volume).
ensure_var() {
    local name=$1 value=$2 tmp
    if [[ -n "$(env_value "$name")" ]]; then
        return
    fi
    if grep -q "^$name=" "$env_file"; then
        tmp=$(mktemp "$env_file.XXXXXX")
        grep -v "^$name=" "$env_file" >"$tmp" || true
        cat "$tmp" >"$env_file"
        rm -f -- "$tmp"
    fi
    printf '%s=%s\n' "$name" "$value" >>"$env_file"
    added+=("$name")
}
# Optional variables are written once with their default value (they may stay empty).
ensure_optional_var() {
    local name=$1 value=$2
    grep -q "^$name=" "$env_file" || { printf '%s=%s\n' "$name" "$value" >>"$env_file"; added+=("$name"); }
}

ensure_var MSSQL_SA_PASSWORD "$(random_password 24)"
ensure_var META_DB_PASSWORD "$(random_password 24)"
ensure_var STORAGE_DB_PASSWORD "$(random_password 24)"
ensure_optional_var STORAGE_DB_HOST mssql
ensure_optional_var STORAGE_DB_SA_PASSWORD ""
ensure_var MINIO_ROOT_USER filegrid-root
ensure_var MINIO_ROOT_PASSWORD "$(random_password 32)"
ensure_var MINIO_BUCKET filegrid
ensure_var S3_ACCESS_KEY filegrid-app
ensure_var S3_SECRET_KEY "$(random_password 32)"
ensure_var FTP_USER filegrid
ensure_var FTP_PASSWORD "$(random_password 24)"
ensure_var GRAFANA_ADMIN_PASSWORD "$(random_password 20)"
ensure_var JWT_SECRET "$(random_base64 48)"
ensure_var DOC_ENCRYPTION_KEY "$(random_base64 32)"
ensure_var DOWNLOAD_LINK_SECRET "$(random_base64 48)"
test_users=(dispecer:DISPATCH teren:FIELD racordari:CONNECTIONS contor:METER_SERVICE admin:ADMIN)
for entry in "${test_users[@]}"; do
    user=${entry%%:*}
    ensure_var "FILEGRID_USER_$(printf '%s' "$user" | tr '[:lower:]' '[:upper:]')_PASSWORD" "$(random_password 16)"
done
chmod 600 "$env_file" 2>/dev/null || true

if $created_env; then
    info ".env created with random values ($env_file)."
elif ((${#added[@]} > 0)); then
    info ".env updated with: ${added[*]}"
else
    info ".env already exists; using it unchanged."
fi

# --- 3. Start ---------------------------------------------------------------------------------------------------
info "docker compose up -d --build (the first build takes a few minutes)"
if ! docker compose up -d --build; then
    printf '\nLast lines from mssql-init and minio-init:\n' >&2
    docker compose logs --no-color --tail 30 mssql-init minio-init >&2 || true
    fail "docker compose up failed (details above; docker compose logs <service>)."
fi

# --- 4. Wait for health -----------------------------------------------------------------------------------------
# The api container healthcheck uses GET /api/v1/health (UP when api and FileGridMeta respond); then the same
# endpoint is checked through nginx over HTTPS, the way the UI sees it.
info "waiting for api health (up to ${health_timeout}s)"
deadline=$((SECONDS + health_timeout))
while :; do
    ids=$(docker compose ps -q api)
    healthy=0 total=0
    for id in $ids; do
        total=$((total + 1))
        [[ "$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{end}}' "$id")" == healthy ]] &&
            healthy=$((healthy + 1))
    done
    if ((total > 0 && healthy == total)); then
        break
    fi
    if ((SECONDS >= deadline)); then
        docker compose ps -a >&2 || true
        docker compose logs --no-color --tail 40 api >&2 || true
        fail "api did not become healthy within ${health_timeout}s."
    fi
    sleep 3
done
info "api: $healthy/$total instances healthy"

if command -v curl >/dev/null 2>&1; then
    # nginx re-resolves api every 5 s, so the first requests may return 502/503 for a few seconds.
    nginx_deadline=$((SECONDS + 60))
    while :; do
        code=$(curl -ks --max-time 5 -o /dev/null -w '%{http_code}' https://localhost/api/v1/health || true)
        [[ "$code" == 200 ]] && break
        if ((SECONDS >= nginx_deadline)); then
            docker compose logs --no-color --tail 20 nginx >&2 || true
            fail "GET https://localhost/api/v1/health -> ${code:-no response} (api is healthy, but nginx is not serving it)."
        fi
        sleep 2
    done
    info "GET https://localhost/api/v1/health -> 200"
fi

# --- 5. Summary -------------------------------------------------------------------------------------------------
cat <<EOF

FileGrid PPC is running:  https://localhost   (self-signed certificate: accept it in the browser)
Grafana:                  https://localhost/grafana/   (user admin, password GRAFANA_ADMIN_PASSWORD from .env)

Test users (passwords are in .env):
EOF
for entry in "${test_users[@]}"; do
    user=${entry%%:*} role=${entry#*:}
    if $show_passwords; then
        var="FILEGRID_USER_$(printf '%s' "$user" | tr '[:lower:]' '[:upper:]')_PASSWORD"
        printf '  %-10s %-14s %s\n' "$user" "$role" "$(env_value "$var")"
    else
        printf '  %-10s %s\n' "$user" "$role"
    fi
done
printf '\nStop: docker compose down    Full reset (deletes all data): docker compose down -v\n'
