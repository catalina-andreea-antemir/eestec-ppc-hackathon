package ro.filegrid.storage;

import java.io.InputStream;
import java.util.List;

import ro.filegrid.domain.StorageType;

/**
 * Chunked upload on a storage backend (ADR-003; S3: native multipart, FTP: one file per chunk + manifest,
 * DB: chunks appended to {@code blob_chunks}). The resulting object is then read with
 * {@link StorageAdapter#get(String, ByteRange)} under the same key.
 *
 * <h2>Who owns the state</h2>
 * Session state lives in FileGridMeta ({@code upload_sessions}, {@code upload_chunks}) and is managed by the caller
 * (the {@code /uploads} flow, C7): {@code next_chunk}, the lease, per-chunk hashes, ETags. The writer keeps <b>no</b>
 * in-memory state between calls: any {@code api} instance can continue an upload started by another one, using only
 * {@link ChunkedUpload} (rebuilt from the {@code upload_sessions} row). Nothing is written to the instance's disk.
 *
 * <h2>What the caller guarantees</h2>
 * <ul>
 *   <li>Calls for the same upload are <b>serialized</b> (per-upload lease): never two concurrent {@code append}
 *       calls on the same session.</li>
 *   <li>Chunks arrive <b>in order</b>, starting at 1; the only possible repeat is the last chunk sent (a resend
 *       after an error between the storage write and the DB confirmation, or after a chunk cut off midway).</li>
 *   <li>{@code length} is exactly {@link ChunkedUpload#expectedLength(int)}: {@code chunkSize}, and the last chunk
 *       may be smaller. {@code chunkSize} is between 5 MiB and 64 MiB (validated by PolicyEngine).</li>
 * </ul>
 *
 * <p>Errors follow the {@link StorageAdapter} rules ({@link StorageUnavailableException} -> 503 with
 * {@code Retry-After} and resume; everything else is a {@link StorageException}).
 */
public interface ChunkedWriter {

    /** The implemented storage; unique among {@code ChunkedWriter} beans. */
    StorageType type();

    /**
     * Starts an upload. Writes no data yet (or only what the storage requires: S3 {@code CreateMultipartUpload}).
     *
     * @param key       key of the final object (UUID generated by the caller)
     * @param totalSize total size announced at {@code POST /uploads}
     * @param chunkSize nominal chunk size, from the policy
     * @return the storage's upload reference, saved by the caller in {@code upload_sessions.storage_upload_ref}
     *         (at most 1024 characters): S3 = {@code UploadId}; FTP = the chunk directory / prefix; DB = usually the key
     *         itself. No passwords or personal data.
     */
    String open(String key, long totalSize, int chunkSize);

    /**
     * Writes chunk {@code n} as a stream, without a chunk-sized buffer (a chunk can be up to 64 MiB). If chunk
     * {@code n} was already written (fully or partially), its content is <b>replaced</b>: resending is safe. On failure
     * chunk {@code n} may be left partial; the next {@code append(n)} rewrites it.
     *
     * <ul>
     *   <li>S3: {@code UploadPart} with {@code partNumber = n}; the returned ETag goes into {@link ChunkReceipt#etag()}.</li>
     *   <li>FTP: a temp file per chunk, atomically renamed ({@code RNFR}/{@code RNTO}) only once complete.</li>
     *   <li>DB: the chunk's {@code blob_chunks} rows, with {@code chunk_offset} starting at
     *       {@link ChunkedUpload#offsetOf(int)}; on resend the rows in the chunk's range are deleted first, in the same
     *       transaction.</li>
     * </ul>
     *
     * @param upload the session (key, reference, sizes)
     * @param n      chunk number, from 1 to {@link ChunkedUpload#totalChunks()}
     * @param data   request body; the caller owns and closes it
     * @param length exact number of bytes to read from {@code data}
     * @return the chunk confirmation (size, ETag on S3), saved by the caller in {@code upload_chunks}
     */
    ChunkReceipt append(ChunkedUpload upload, int n, InputStream data, long length);

    /**
     * Completes the upload: on success the object under {@link ChunkedUpload#key()} is complete and visible to
     * {@link StorageAdapter#exists(String)} and {@link StorageAdapter#get(String, ByteRange)}. The caller computes the
     * final hash by streaming the object.
     *
     * <p><b>Idempotent</b>: a second {@code finish} after a successful one (e.g. the DB went down between finish and
     * the session confirmation) does not damage the object and does not throw.
     *
     * @param upload the session
     * @param chunks confirmations of every chunk, in order, from 1 to {@code totalChunks} (from {@code upload_chunks})
     * @return size of the final object in bytes (equal to {@link ChunkedUpload#totalSize()})
     */
    long finish(ChunkedUpload upload, List<ChunkReceipt> chunks);

    /**
     * Abandons the upload and deletes everything written (S3 {@code AbortMultipartUpload}, deleting the FTP chunks /
     * {@code blob_chunks} rows). Idempotent; used by {@code POST /uploads/{id}/abort}, by abandonment after 10 minutes of
     * storage downtime and by the cleanup of sessions idle for more than 24 h.
     */
    void abort(ChunkedUpload upload);
}
