package ro.filegrid.storage;

import java.io.InputStream;

import ro.filegrid.domain.StorageType;

/**
 * Common contract of the 3 storage backends (implementations: {@code storage/s3/S3Adapter},
 * {@code storage/ftp/FtpAdapter}, {@code storage/db/DbStorageAdapter}). Each implementation is a Spring bean and
 * usually also implements {@link ChunkedWriter}; {@link StorageAdapterRegistry} finds them by {@link #type()}.
 *
 * <h2>Rules shared by every method</h2>
 * <ul>
 *   <li><b>Streaming</b>: no file or chunk is ever held whole in memory. Use a fixed buffer (e.g. 64 KiB) or the
 *       storage's streaming API ({@code setBinaryStream} / {@code getBinaryStream}, {@code RequestBody.fromInputStream},
 *       {@code storeFile}). Acceptance test: 1.1 GB with {@code -Xmx256m}.</li>
 *   <li><b>The key</b> ({@code key}) is generated by the caller (a UUID, see {@link StorageKeys}); the adapter never
 *       changes it and may map it internally to a path / object name. Whatever the adapter writes under a key is
 *       read back only with the same key.</li>
 *   <li><b>The SHA-256 hash</b> and the metadata ({@code files} table) are the caller's job (the ingest flow);
 *       the adapter only moves bytes.</li>
 *   <li><b>Errors</b>: storage unavailable (connection refused, timeout, OFFLINE database) ->
 *       {@link StorageUnavailableException}; missing key on read -> {@link StorageObjectNotFoundException};
 *       anything else -> {@link StorageException}. JDBC / FTP / AWS exceptions are wrapped, never leaked directly.
 *       Messages contain no passwords, keys or personal data.</li>
 *   <li><b>Threads</b>: one instance is used concurrently by many requests, so it keeps no per-request state in
 *       fields. Connections come from a pool (JDBC, S3) or are opened per operation (FTP).</li>
 *   <li><b>Resilience</b> (retry, circuit breaker, fallback to the secondary storage) sits above the adapter (C11);
 *       the adapter never retries indefinitely on its own and uses short timeouts.</li>
 * </ul>
 */
public interface StorageAdapter {

    /** The implemented storage; unique among {@code StorageAdapter} beans. */
    StorageType type();

    /**
     * Writes a whole object, streaming exactly {@code length} bytes from {@code data}.
     *
     * <ul>
     *   <li>The caller owns {@code data} and closes it; the adapter never reads more than {@code length} bytes.</li>
     *   <li>If the source ends before {@code length} bytes, the write fails with {@link StorageException}.</li>
     *   <li>If {@code key} already exists, its content is replaced entirely (a retry with the same key is safe).</li>
     *   <li>Atomic from a reader's point of view: on failure, {@link #exists(String)} returns {@code false} for a new
     *       key (DB: transaction; FTP: temp name + {@code RNFR}/{@code RNTO}; S3: native).</li>
     * </ul>
     *
     * @param key         object key, valid per {@link StorageKeys#requireValid(String)}
     * @param data        the source, read once, sequentially
     * @param length      exact number of bytes, at least 1 (empty files are rejected by the caller with 400:
     *                    {@code files.size_bytes > 0}, and {@code blob_chunks} has no empty rows)
     * @param contentType MIME type (used by S3; FTP and DB may ignore it, it is kept in {@code files} anyway)
     * @return number of bytes written (equal to {@code length})
     * @throws StorageUnavailableException the storage does not respond
     * @throws StorageException            any other error, including a source that is too short
     */
    long put(String key, InputStream data, long length, String contentType);

    /**
     * Opens the object for streaming reads, whole or just a range (for {@code Range} / {@code 206}).
     *
     * <ul>
     *   <li>The returned stream holds its resources open (JDBC connection, FTP session, S3 response) until
     *       {@code close()}; the caller always closes it (try-with-resources), including when the HTTP client gives up.</li>
     *   <li>Returns bytes {@code [range.offset(), range.offset() + range.length())}, stopping at the end of the object
     *       if the range goes past it; an {@code offset} greater than or equal to the size yields an empty stream.
     *       Validating {@code Range} against the size (416) is the caller's job, using {@code files.size_bytes}.</li>
     *   <li>The implementation seeks straight to the offset (S3 range GET, FTP {@code REST}, DB: the {@code blob_chunks}
     *       rows with a matching {@code chunk_offset}) instead of reading and discarding the preceding bytes.</li>
     *   <li>A missing key is reported when opening, not on the first read. Errors during reading surface as
     *       {@link java.io.IOException} from the stream.</li>
     * </ul>
     *
     * @param key   object key
     * @param range the requested range; {@link ByteRange#full()} for the whole object
     * @throws StorageObjectNotFoundException the key does not exist
     * @throws StorageUnavailableException    the storage does not respond
     */
    InputStream get(String key, ByteRange range);

    /**
     * Deletes the object (and any chunks left over from a chunked upload with the same key). Idempotent: a missing key
     * is not an error. Used for compensation (write succeeded but metadata failed) and for cleanup.
     *
     * @return {@code true} if something was deleted, {@code false} if the object did not exist
     * @throws StorageUnavailableException the storage does not respond
     */
    boolean delete(String key);

    /**
     * Whether a complete object exists under this key (written with {@link #put} or completed with
     * {@link ChunkedWriter#finish}). Chunks of an unfinished upload do not count.
     *
     * @throws StorageUnavailableException the storage does not respond
     */
    boolean exists(String key);

    /**
     * Quick check (a minimal operation: {@code SELECT 1}, {@code NOOP}, {@code HeadBucket}) with a timeout of at most
     * 2 seconds. <b>Never throws</b>: any error becomes {@link StorageHealth#down}. Called periodically for
     * {@code filegrid_storage_up}, {@code /admin/health} and fallback selection (C11).
     */
    StorageHealth health();
}
