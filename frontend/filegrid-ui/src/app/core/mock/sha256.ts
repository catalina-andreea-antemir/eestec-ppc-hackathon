const INITIAL = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];

export interface Sha256State {
  h: number[];
  /** Octeții rămași (sub 64) din ultimul bloc incomplet. */
  pending: number[];
  length: number;
}

export class Sha256 {
  private readonly h: Uint32Array;
  private pending: Uint8Array;
  private length: number;
  private readonly w = new Uint32Array(64);

  constructor(state?: Sha256State) {
    this.h = Uint32Array.from(state?.h ?? INITIAL);
    this.pending = Uint8Array.from(state?.pending ?? []);
    this.length = state?.length ?? 0;
  }

  state(): Sha256State {
    return { h: Array.from(this.h), pending: Array.from(this.pending), length: this.length };
  }

  update(data: Uint8Array): this {
    this.length += data.length;
    let offset = 0;
    if (this.pending.length > 0) {
      const needed = 64 - this.pending.length;
      if (data.length < needed) {
        this.pending = concat(this.pending, data);
        return this;
      }
      this.block(concat(this.pending, data.subarray(0, needed)), 0);
      offset = needed;
    }
    for (; offset + 64 <= data.length; offset += 64) {
      this.block(data, offset);
    }
    this.pending = data.slice(offset);
    return this;
  }

  hex(): string {
    const copy = new Sha256(this.state());
    const bitLength = copy.length * 8;
    const padLength = (copy.pending.length < 56 ? 56 : 120) - copy.pending.length;
    const tail = new Uint8Array(padLength + 8);
    tail[0] = 0x80;
    const view = new DataView(tail.buffer);
    view.setUint32(padLength, Math.floor(bitLength / 2 ** 32));
    view.setUint32(padLength + 4, bitLength >>> 0);
    copy.update(tail);
    return Array.from(copy.h, (x) => x.toString(16).padStart(8, '0')).join('');
  }

  private block(data: Uint8Array, offset: number): void {
    const w = this.w;
    for (let i = 0; i < 16; i++) {
      const j = offset + i * 4;
      w[i] = (data[j] << 24) | (data[j + 1] << 16) | (data[j + 2] << 8) | data[j + 3];
    }
    for (let i = 16; i < 64; i++) {
      const a = w[i - 15];
      const b = w[i - 2];
      const s0 = ((a >>> 7) | (a << 25)) ^ ((a >>> 18) | (a << 14)) ^ (a >>> 3);
      const s1 = ((b >>> 17) | (b << 15)) ^ ((b >>> 19) | (b << 13)) ^ (b >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let [a, b, c, d, e, f, g, h] = this.h;
    for (let i = 0; i < 64; i++) {
      const s1 = ((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7));
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + s1 + ch + K[i] + w[i]) | 0;
      const s0 = ((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10));
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (s0 + maj) | 0;
      h = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }
    this.h[0] += a;
    this.h[1] += b;
    this.h[2] += c;
    this.h[3] += d;
    this.h[4] += e;
    this.h[5] += f;
    this.h[6] += g;
    this.h[7] += h;
  }
}

function concat(a: Uint8Array, b: Uint8Array): Uint8Array {
  const out = new Uint8Array(a.length + b.length);
  out.set(a);
  out.set(b, a.length);
  return out;
}

export async function sha256Hex(data: BufferSource): Promise<string> {
  const digest = await crypto.subtle.digest('SHA-256', data);
  return Array.from(new Uint8Array(digest), (x) => x.toString(16).padStart(2, '0')).join('');
}
